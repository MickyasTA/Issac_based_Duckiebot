@dataclass(frozen=True)
class RobotParams:
    """Duckiebot dimensional and actuator constants (SPEC v2 S2 and S3.2).

    All lengths are metres, masses kilograms, inertias kg.m^2, torques N.m, angular rates rad/s.
    Frames follow REP-103 (x forward, y left, z up) with ``base_link`` at the wheel-axle midpoint,
    which sits ``wheel_radius`` above the ground when the robot is level.
    """

    wheel_radius: float = 0.0318
    wheel_separation: float = 0.100
    wheel_width: float = 0.027
    base_mass: float = 1.000
    wheel_mass: float = 0.050
    base_com: tuple[float, float, float] = (-0.015, 0.0, 0.015)
    base_inertia_diag: tuple[float, float, float] = (1.877e-3, 3.169e-3, 4.108e-3)
    wheel_inertia_diag: tuple[float, float, float] = (1.568e-5, 2.528e-5, 1.568e-5)
    chassis_size: tuple[float, float, float] = (0.18, 0.13, 0.075)
    chassis_center: tuple[float, float, float] = (-0.015, 0.0, 0.0267)
    caster_radius: float = 0.0165
    caster_center: tuple[float, float, float] = (-0.085, 0.0, -0.0153)
    camera_block_size: tuple[float, float, float] = (0.03, 0.03, 0.03)
    marker_radius: float = 0.025
    marker_center: tuple[float, float, float] = (-0.03, 0.0, 0.09)
    effort_limit: float = 0.15
    velocity_limit: float = 35.0
    joint_damping: float = 0.05
    joint_armature: float = 2.0e-4
    joint_friction: float = 0.010
    passive_joint_damping: float = 0.0
    motor_k: float = 27.0
    wheel_friction: float = 1.0
    caster_friction: float = 0.0
    robot_width: float = 0.131
    encoder_ticks_per_rev: int = 135
    v_max: float = 0.6
    omega_max: float = 4.0
    camera_pos: tuple[float, float, float] = (0.078, 0.0, 0.0692)
    camera_pitch_down_deg: float = 25.3
    camera_focal_px: float = 65.98
    camera_fovy_deg: float = 88.26
    clipping_range: tuple[float, float] = (0.05, 6.0)
    brake_dw_max: float = 12.0
    pwm_release_duty: float = 0.01
    actuation_delay_s: float = 0.150
    base_link_name: str = "base_link"
    left_wheel_link_name: str = "left_wheel_link"
    right_wheel_link_name: str = "right_wheel_link"
    left_wheel_joint_name: str = "left_wheel_joint"
    right_wheel_joint_name: str = "right_wheel_joint"

    @property
    def base_height(self) -> float:
        """Height of ``base_link`` above the ground plane when level (equals the wheel radius)."""
        return self.wheel_radius

    @property
    def ground_clearance(self) -> float:
        """Gap between the bottom face of the chassis collision box and the ground."""
        return self.base_height + self.chassis_center[2] - 0.5 * self.chassis_size[2]

    def validate(self) -> None:
        """Assert the geometric invariants SPEC v2 S2 pins down.

        Raises:
            ValueError: if the caster is not tangent to the ground, if the chassis clearance is not
                the specified 21 mm, or if a mass or limit is non-positive.
        """
        caster_contact = self.base_height + self.caster_center[2] - self.caster_radius
        if abs(caster_contact) > 1e-9:
            raise ValueError(
                f"caster is not tangent to the ground: contact z = {caster_contact:.6f} m; "
                f"S2 requires the caster centre exactly one radius above the ground"
            )
        if abs(self.ground_clearance - 0.021) > 1e-6:
            raise ValueError(
                f"chassis ground clearance {self.ground_clearance:.6f} m != 0.021 m (S2 item 24)"
            )
        positive = (
            "base_mass",
            "wheel_mass",
            "wheel_radius",
            "wheel_separation",
            "effort_limit",
            "velocity_limit",
            "joint_armature",
        )
        for name in positive:
            if getattr(self, name) <= 0.0:
                raise ValueError(f"{name} must be positive, got {getattr(self, name)!r}")
        if self.joint_friction < 0.0 or self.joint_damping < 0.0:
            raise ValueError("joint friction and damping must be non-negative")


@dataclass(frozen=True)
class SimParams:
    """Integrator and rate settings (SPEC v2 S5.2 and S8.1).

    ``physics_dt`` and ``decimation`` are deliberately identical to the Isaac Lab side: critic item
    J flagged the v1 mismatch (Isaac 1/120 x 8 versus MuJoCo 1/240 x 16) as a confound hiding inside
    the headline C1-vs-C5 delta. :class:`duckiebot_rl.sim2sim.env.MjEnvCfg` re-exposes them so the
    confound can be re-introduced deliberately as an ablation, never by accident.
    """

    physics_dt: float = 1.0 / 240.0
    decimation: int = 16
    integrator: str = "implicitfast"
    cone: str = "elliptic"
    impratio: float = 10.0
    solver: str = "Newton"
    iterations: int = 5
    ls_iterations: int = 20
    gravity: tuple[float, float, float] = (0.0, 0.0, -9.81)
    solref_wheel: tuple[float, float] = (0.004, 1.0)
    solref_default: tuple[float, float] = (0.005, 1.0)
    solimp_wheel: tuple[float, float, float] = (0.97, 0.995, 0.001)
    solimp_default: tuple[float, float, float] = (0.95, 0.99, 0.001)

    @property
    def control_dt(self) -> float:
        """Seconds per control step."""
        return self.physics_dt * self.decimation

    @property
    def control_hz(self) -> float:
        """Control frequency in Hz (15.0 for the SPEC v2 defaults)."""
        return 1.0 / self.control_dt

    def validate(self) -> None:
        """Assert the S8.3 item-3 rate requirements.

        Raises:
            ValueError: if the decimation is not a positive integer, or the integrator is an
                explicit one. SPEC v2 S8.1 locks ``implicitfast`` for a *structural* reason: PhysX
                integrates its implicit velocity drive implicitly, and matching structure is the
                job of this package. The v1 justification (a measured -87% forward speed under
                ``Euler``) does not reproduce at the SPEC v2 armature, and
                ``tests/unit/test_mj_kinematics.py`` carries that measurement; the lock stays
                because the stability margin is under a factor of three and system identification
                is free to move both the armature and the servo gain.
        """
        if self.decimation < 1 or int(self.decimation) != self.decimation:
            raise ValueError(f"decimation must be a positive integer, got {self.decimation!r}")
        if self.physics_dt <= 0.0:
            raise ValueError("physics_dt must be positive")
        if self.integrator not in ("implicitfast", "implicit", "RK4"):
            raise ValueError(
                f"integrator {self.integrator!r} is not allowed; SPEC v2 S8.1 locks 'implicitfast' "
                f"because MuJoCo integrates the <velocity kv> gain explicitly under Euler"
            )


