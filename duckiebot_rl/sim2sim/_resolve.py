def _coerce(field: dataclasses.Field, value: Any) -> Any:
    """Coerce a value pulled from a foreign module into the declared dataclass field type."""
    if isinstance(value, (list, tuple)):
        return tuple(float(v) for v in value)
    if field.type in ("str", str):
        return str(value)
    if field.type in ("int", int):
        return int(value)
    return float(value)


def _adapt(source: Any, target: Any, adapter: dict[str, tuple[str, ...]]) -> tuple[Any, list[str]]:
    """Rebuild ``target`` from ``source`` using ``adapter``; return it plus the unresolved fields.

    Args:
        source: the foreign parameter object (or a mapping).
        target: the sim2sim dataclass instance holding the fallback defaults.
        adapter: mapping of target field name to candidate source attribute names.

    Returns:
        ``(new_target, missing)`` where ``missing`` lists target fields that had no source value.
    """
    if isinstance(source, dict):

        def getter(key: str) -> Any:
            return source.get(key)
    else:

        def getter(key: str) -> Any:
            return getattr(source, key, None)

    by_name = {f.name: f for f in dataclasses.fields(target)}
    values: dict[str, Any] = {}
    missing: list[str] = []
    for target_field, candidates in adapter.items():
        for key in candidates:
            raw = getter(key)
            if raw is None:
                continue
            values[target_field] = _coerce(by_name[target_field], raw)
            break
        else:
            missing.append(target_field)
    return dataclasses.replace(target, **values), missing


def resolve_robot_params(strict: bool = False) -> tuple[RobotParams, str]:
    """Return the authoritative :class:`RobotParams` and a human-readable provenance string.

    Args:
        strict: if True, raise instead of falling back to the SPEC v2 literals.

    Returns:
        ``(params, provenance)`` where ``provenance`` names the module the numbers came from.

    Raises:
        SharedModuleUnavailable: if ``strict`` and no shared params module can be imported.
        ValueError: if a shared params module exists but does not expose the whole adapter, which
            would leave the MJCF a silent mixture of authoritative and fallback numbers.
    """
    global PARAMS_SOURCE
    for mod_name in _PARAM_MODULES:
        module = _try_import(mod_name)
        if module is None:
            continue
        source: Any = None
        for attr in _PARAM_ATTRS:
            source = getattr(module, attr, None)
            if source is not None:
                break
        if source is None:
            source = module
        params, missing = _adapt(source, _FALLBACK_ROBOT, _PARAM_ADAPTER)
        if missing:
            raise ValueError(
                f"{mod_name} was imported but does not expose {missing}. sim2sim refuses to mix "
                f"authoritative and fallback robot numbers. Extend _PARAM_ADAPTER in "
                f"duckiebot_rl/sim2sim/_resolve.py (requires [assets] + [sim2sim] agreement)."
            )
        params.validate()
        PARAMS_SOURCE = f"{mod_name}.{type(source).__name__}"
        return params, PARAMS_SOURCE
    if strict:
        raise SharedModuleUnavailable(
            "no shared robot-parameter module found; the [assets] engineer must land one of "
            + " or ".join(_PARAM_MODULES)
        )
    warnings.warn(
        "duckiebot_rl.assets.params is not importable; sim2sim is using the SPEC v2 S2/S3.2 "
        "literal fallback. Delete duckiebot_rl.sim2sim._resolve._FALLBACK_ROBOT once [assets] "
        "lands the real module, so Isaac and MuJoCo cannot drift apart.",
        SpecFallbackWarning,
        stacklevel=2,
    )
    _FALLBACK_ROBOT.validate()
    PARAMS_SOURCE = "SPEC v2 S2/S3.2 fallback (duckiebot_rl.sim2sim._resolve)"
    return _FALLBACK_ROBOT, PARAMS_SOURCE


def resolve_sim_params(base: SimParams | None = None) -> tuple[SimParams, str]:
    """Return :class:`SimParams` with the rate fields taken from the shared params module.

    Only ``physics_dt`` and ``decimation`` are shared: the integrator, cone and solver settings are
    MuJoCo-specific and have no Isaac counterpart. Taking the rates from the same object as the
    Isaac env is what removes critic item J's integration-rate confound.

    Args:
        base: a :class:`SimParams` supplying the MuJoCo-only fields; defaults to the SPEC v2 set.

    Returns:
        ``(sim_params, provenance)``.
    """
    target = base if base is not None else SimParams()
    for mod_name in _PARAM_MODULES:
        module = _try_import(mod_name)
        if module is None:
            continue
        source: Any = None
        for attr in _PARAM_ATTRS:
            source = getattr(module, attr, None)
            if source is not None:
                break
        adapted, missing = _adapt(source if source is not None else module, target, _SIM_ADAPTER)
        if not missing:
            adapted.validate()
            return adapted, f"{mod_name} (rates)"
    target.validate()
    return target, "SPEC v2 S5.2/S8.1 fallback"


def _resolve_any(names: Iterable[str], what: str, required_attrs: Iterable[str] = ()) -> ModuleType:
    """Import the first module in ``names`` exposing every attribute in ``required_attrs``."""
    tried = list(names)
    for name in tried:
        module = _try_import(name)
        if module is None:
            continue
        if all(hasattr(module, attr) for attr in required_attrs):
            return module
    raise SharedModuleUnavailable(
        f"{what} is unavailable. sim2sim requires one of {tried} exposing "
        f"{list(required_attrs)}. That module is owned by another engineer; it must land before "
        f"the MuJoCo vision path can claim parity with Isaac."
    )


