"""Cross-team module resolution and the SPEC v2 constant fallback for the sim2sim package.

The whole point of the MuJoCo harness is *parity*: it must be driven by the same numbers and the
same preprocessing code as the Isaac Lab environment. Therefore nothing in ``duckiebot_rl.sim2sim``
is allowed to hardcode a robot dimension. Every value is pulled through
:func:`resolve_robot_params`, which prefers the authoritative module owned by the ``[assets]``
engineer and only falls back to a literal transcription of SPEC v2 S2/S3.2 when that module does
not exist yet.

Resolution order (first hit wins), and what each provides:

===============================  ==========================================================
Shared module                    Provides
===============================  ==========================================================
``duckiebot_rl.assets.params``   robot dimensions / masses / actuator numbers (S2, S3.2)
``duckiebot_rl.dr.preprocess``   S4.3 observation operator chain (torch)
``duckiebot_rl.preprocess``      same, alternative location named by SPEC v2 S6.1
``duckiebot_rl.wrappers.delay``  S5.3 step-2 actuation delay ring / S4.3 step-9 obs delay
``duckiebot_rl.camera_math``     ``quat_cam_ros`` and the MuJoCo ``xyaxes`` derivation (S2)
``duckiebot_rl.city``            map loader, tile textures and lane graph (S3.3)
===============================  ==========================================================

When a module is missing the resolver raises :class:`SharedModuleUnavailable` with the exact import
path that has to land, or emits :class:`SpecFallbackWarning` and continues with the SPEC v2 literal
values when a safe local equivalent exists. ``PARAMS_SOURCE`` records which happened, so a report
generated by :mod:`duckiebot_rl.sim2sim.evaluate` always states its provenance.
"""

