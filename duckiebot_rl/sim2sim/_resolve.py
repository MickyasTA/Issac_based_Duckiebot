# ---------------------------------------------------------------------------------- camera math
def quat_cam_ros(pitch_down_rad: float) -> tuple[float, float, float, float]:
    """Return the ``(w, x, y, z)`` quaternion of the ROS optical frame expressed in ``base_link``.

    The ROS camera convention is +Z forward, +X right, +Y down. ``pitch_down_rad`` is a positive
    scalar meaning "nose down"; no other code in the sim2sim package touches a camera sign.

    Golden values pinned by SPEC v2 S2: pitch 0 gives ``(0.5, -0.5, 0.5, -0.5)`` and pitch
    25.3 deg gives ``(0.37837, -0.59736, 0.59736, -0.37837)``.

    Args:
        pitch_down_rad: downward camera pitch in radians.

    Returns:
        The unit quaternion as ``(w, x, y, z)``.

    Raises:
        ValueError: if a shared ``camera_math`` module returns something that is not a quaternion,
            or if the pitch is outside the representable open range (-90 deg, +90 deg).
    """
    shared = resolve_camera_math()
    if shared is not None and hasattr(shared, "quat_cam_ros"):
        q = tuple(float(v) for v in shared.quat_cam_ros(pitch_down_rad))
        if len(q) != 4:
            raise ValueError(f"camera_math.quat_cam_ros returned {len(q)} components, expected 4")
        return q  # type: ignore[return-value]
    if not -math.pi / 2.0 < pitch_down_rad < math.pi / 2.0:
        raise ValueError(f"pitch_down_rad {pitch_down_rad!r} is outside (-pi/2, +pi/2)")
    # The target rotation has columns [right, down, forward] with right = (0, -1, 0),
    # down = (-sin p, 0, -cos p) and forward = (cos p, 0, -sin p). Its trace is -sin p, so the
    # standard trace formula collapses to the closed form below (checked against both S2 goldens).
    sin_p = math.sin(pitch_down_rad)
    lo = math.sqrt(1.0 - sin_p) / 2.0
    hi = math.sqrt(1.0 + sin_p) / 2.0
    return (lo, -hi, hi, -lo)


def _quat_columns(q: tuple[float, float, float, float]) -> tuple[tuple[float, ...], ...]:
    """Return the three columns of the rotation matrix of quaternion ``(w, x, y, z)``."""
    w, x, y, z = q
    col0 = (1 - 2 * (y * y + z * z), 2 * (x * y + w * z), 2 * (x * z - w * y))
    col1 = (2 * (x * y - w * z), 1 - 2 * (x * x + z * z), 2 * (y * z + w * x))
    col2 = (2 * (x * z + w * y), 2 * (y * z - w * x), 1 - 2 * (x * x + y * y))
    return col0, col1, col2


def mj_camera_xyaxes(pitch_down_rad: float) -> tuple[float, ...]:
    """Return the MuJoCo ``xyaxes`` (6 numbers) for a camera pitched ``pitch_down_rad`` down.

    MuJoCo cameras look along -Z of their own frame with +Y up, so ``xyaxes`` is ``[right ; up]``
    expressed in the parent body frame. Both vectors are derived from :func:`quat_cam_ros` so that
    Isaac, MuJoCo and the deploy node cannot disagree: the ROS optical X axis *is* MuJoCo's camera
    X, and MuJoCo's camera Y is the negated ROS optical Y (down becomes up).

    Args:
        pitch_down_rad: downward camera pitch in radians.

    Returns:
        ``(rx, ry, rz, ux, uy, uz)``.
    """
    right, down, _forward = _quat_columns(quat_cam_ros(pitch_down_rad))
    up = tuple(-v for v in down)
    return tuple(right) + up


def mj_camera_forward(pitch_down_rad: float) -> tuple[float, ...]:
    """Return the camera viewing direction in the parent body frame (ROS optical +Z)."""
    _right, _down, forward = _quat_columns(quat_cam_ros(pitch_down_rad))
    return tuple(forward)


