class SpecFallbackWarning(UserWarning):
    """Warning issued when a shared module is absent and SPEC v2 literals are used instead."""


class SharedModuleUnavailable(ImportError):
    """A shared module that has no safe local substitute is missing from the interpreter."""


#: Modules that exist but raised while importing, as ``name -> repr(exception)``. A shared module
#: that is *absent* and one that is *broken* are different problems with different owners, and the
#: harness used to report both as "not importable"; this records the difference so the fallback
#: warning can name the real cause.
IMPORT_FAILURES: dict[str, str] = {}


def _try_import(name: str) -> ModuleType | None:
    """Import ``name`` and return the module, or None when it cannot be imported.

    A module that is simply absent returns None quietly, which is the expected state while another
    team's module has not landed yet. A module that EXISTS but raises (a syntax error, or a missing
    third-party dependency such as torch in the tools venv) is a different failure: it is recorded
    in :data:`IMPORT_FAILURES` and reported through a :class:`SpecFallbackWarning` naming the
    exception, so it cannot masquerade as "not landed yet" and silently downgrade the harness to
    the SPEC literals.

    Args:
        name: the dotted module path.

    Returns:
        The imported module, or None.
    """
    try:
        return importlib.import_module(name)
    except ModuleNotFoundError as exc:
        absent = exc.name is None or name == exc.name or name.startswith(f"{exc.name}.")
        if absent:
            return None
        detail = f"{type(exc).__name__}: {exc}"
        IMPORT_FAILURES[name] = detail
        warnings.warn(
            f"{name} exists but failed to import ({detail}). sim2sim is treating it as absent and "
            f"will fall back to the SPEC v2 literals. This is a broken dependency, not a module "
            f"that has yet to land.",
            SpecFallbackWarning,
            stacklevel=2,
        )
        return None
    except Exception as exc:
        detail = f"{type(exc).__name__}: {exc}"
        IMPORT_FAILURES[name] = detail
        warnings.warn(
            f"{name} exists but raised while importing ({detail}). sim2sim is treating it as "
            f"absent and will fall back to the SPEC v2 literals. Fix the module: the fallback is "
            f"not a substitute for the shared numbers.",
            SpecFallbackWarning,
            stacklevel=2,
        )
        return None


